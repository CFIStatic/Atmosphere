/**
 * Generate src/campaigns/zipCentroids.data.ts — where every US ZIP code is.
 *
 * Run by hand when the table needs refreshing, which is roughly annually:
 *
 *   npx --package=zipcodes@8 node scripts/build-zip-centroids.mjs
 *
 * Not a build step and not a dependency: the output is a constant, and making
 * CI reinstall a ZIP database to recompute it every run would be paying
 * forever for a decision made once.
 *
 * Why bundle this at all, when there is already a geocoder. Nominatim's terms
 * allow one request a second, so locating a territory's ZIPs was rate-limited
 * to a couple of dozen per page load — a franchise with five hundred codes
 * would have taken twenty page loads before its map was complete, and until
 * then weather matching silently fell back to county names. A lookup table
 * makes all of it instant, offline, and the same for everyone. The geocoder
 * stays as the fallback for anything missing here.
 *
 * Data is federalgovernmentzipcodes.us by way of the `zipcodes` package (BSD).
 *
 * Excluded on purpose:
 *   - Military ZIPs (AA/AE/AP). An APO in Germany is not a US location; half
 *     of them carry 0,0, which is a point in the Atlantic.
 *   - Anything at exactly 0,0, for the same reason.
 * Pacific and Caribbean territories are kept — they are real places with real
 * coordinates, even though the Albers USA projection has nowhere to draw them.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const { codes } = require('zipcodes/lib/codes.js');

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'campaigns', 'zipCentroids.data.ts');

const MILITARY = new Set(['AA', 'AE', 'AP']);

const rows = Object.values(codes)
  .filter(
    (c) =>
      c &&
      c.country === 'US' &&
      /^[0-9]{5}$/.test(String(c.zip)) &&
      !MILITARY.has(c.state) &&
      Number.isFinite(+c.latitude) &&
      Number.isFinite(+c.longitude) &&
      (+c.latitude !== 0 || +c.longitude !== 0),
  )
  .map((c) => [
    String(c.zip),
    Math.round(+c.latitude * 1e4),
    Math.round(+c.longitude * 1e4),
    String(c.state || '').toUpperCase(),
  ])
  .sort((a, b) => a[0].localeCompare(b[0]));

// States as an index into a short dictionary: two letters per row would be
// 84KB of "TX" repeated, and this is a tenth of that. City names were
// considered and dropped — dictionary-encoded they still cost half a megabyte,
// which is a lot to pay for a tooltip.
const STATES = [...new Set(rows.map((r) => r[3]))].sort();
const stateIndex = new Map(STATES.map((s, i) => [s, i]));

// Delta-encoded in base 36. ZIP codes are geographic, so consecutive codes are
// usually neighbours and the deltas are tiny — this halves the file for the
// cost of three subtractions per row at startup.
let lastZip = 0;
let lastLat = 0;
let lastLon = 0;
const packed = rows
  .map(([zip, lat, lon, state]) => {
    const part = [
      (Number(zip) - lastZip).toString(36),
      (lat - lastLat).toString(36),
      (lon - lastLon).toString(36),
      (stateIndex.get(state) ?? 0).toString(36),
    ].join(',');
    lastZip = Number(zip);
    lastLat = lat;
    lastLon = lon;
    return part;
  })
  .join(';');

console.log(
  `${rows.length} ZIP codes across ${STATES.length} states, ${(packed.length / 1024).toFixed(0)}KB packed`,
);

const file = `/**
 * Every US ZIP code: where it is, and which state it is in.
 *
 * GENERATED by scripts/build-zip-centroids.mjs — do not edit.
 *
 * ${rows.length} codes, delta-encoded in base 36 and decoded once on first use.
 * Positions are ZIP centroids to four decimal places, which is about eleven
 * metres — far finer than a ZIP, which is the thing being located.
 *
 * Source: federalgovernmentzipcodes.us via the \`zipcodes\` package (BSD).
 * Military ZIPs are excluded; an APO in Germany is not a US location.
 */

export interface ZipRecord {
  lat: number;
  lon: number;
  /** Two-letter state or territory. Exact, not inferred from the number. */
  state: string;
}

const STATES = ${JSON.stringify(STATES)};

/** zipDelta,latDelta,lonDelta,stateIndex in base 36, semicolon-separated. */
const PACKED =
  '${packed}';

let table: Map<string, ZipRecord> | null = null;

/**
 * The decoded table, built on first use.
 *
 * Lazy because a process that never looks up a ZIP — most of them — should not
 * pay to parse forty thousand rows at import time.
 */
export function zipTable(): Map<string, ZipRecord> {
  if (table) return table;

  const built = new Map<string, ZipRecord>();
  let zip = 0;
  let lat = 0;
  let lon = 0;

  for (const row of PACKED.split(';')) {
    const [dz, dLat, dLon, si] = row.split(',');
    zip += parseInt(dz, 36);
    lat += parseInt(dLat, 36);
    lon += parseInt(dLon, 36);
    built.set(String(zip).padStart(5, '0'), {
      lat: lat / 1e4,
      lon: lon / 1e4,
      state: STATES[parseInt(si, 36)] ?? '',
    });
  }

  table = built;
  return table;
}

/** Everything known about this ZIP, or null if it is not a US code we hold. */
export function zipRecord(zip: string): ZipRecord | null {
  return zipTable().get(zip) ?? null;
}

/** Where this ZIP is, or null. */
export function centroidFor(zip: string): { lat: number; lon: number } | null {
  const row = zipTable().get(zip);
  return row ? { lat: row.lat, lon: row.lon } : null;
}
`;

writeFileSync(OUT, file);
console.log(`wrote ${OUT} (${(file.length / 1024).toFixed(0)}KB)`);
