/**
 * Generates src/patterns/brandIcons.ts from the simple-icons package.
 *
 * Inlines the path data rather than shipping files or hotlinking a logo CDN:
 * a technician standing in a flooded basement on one bar of signal should not
 * be waiting on forty image requests, and an operational tool should not phone
 * a third party to render its own settings page.
 *
 * Only vendors with a genuine entry are included. Everything else falls back to
 * the brand-coloured monogram, which is the correct outcome for the
 * restoration-specific vendors — they are too niche to appear in any icon set.
 *
 *   node scripts/generate-brand-icons.mjs
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const simpleIcons = require('simple-icons');

const icons = Object.values(simpleIcons).filter((i) => i && i.title && i.path);
const bySlug = new Map(icons.map((i) => [i.title.toLowerCase().replace(/[^a-z0-9]/g, ''), i]));

/**
 * connector id → simple-icons title.
 *
 * Verified by hand. `dash` is deliberately absent: simple-icons has a "Dash"
 * entry, but it is the cryptocurrency, and shipping that for Cotality's
 * restoration job-management product would be worse than showing no logo.
 */
const MATCHES = {
  gmail: 'gmail',
  'google-drive': 'googledrive',
  'google-calendar': 'googlecalendar',
  'quickbooks-online': 'quickbooks',
  'quickbooks-desktop': 'quickbooks',
  xero: 'xero',
  'sage-intacct': 'sage',
  stripe: 'stripe',
  dropbox: 'dropbox',
  box: 'box',
  adp: 'adp',
  gusto: 'gusto',
};

const entries = [];
const missing = [];
for (const [connectorId, slug] of Object.entries(MATCHES)) {
  const icon = bySlug.get(slug);
  if (!icon) {
    missing.push(`${connectorId} (${slug})`);
    continue;
  }
  entries.push({ connectorId, title: icon.title, hex: icon.hex, path: icon.path });
}

if (missing.length) {
  console.error('Missing from simple-icons:', missing.join(', '));
  process.exitCode = 1;
}

const body = entries
  .map(
    (e) =>
      `  '${e.connectorId}': {\n    title: '${e.title.replace(/'/g, "\\'")}',\n    hex: '#${e.hex}',\n    path: '${e.path}',\n  },`,
  )
  .join('\n');

writeFileSync(
  'src/patterns/brandIcons.ts',
  `/**
 * Official brand marks, inlined at build time.
 *
 * GENERATED by scripts/generate-brand-icons.mjs from the simple-icons package —
 * do not edit by hand. Re-run the script to refresh.
 *
 * Each entry is a single 24×24 path meant to be filled with one colour. Vendors
 * absent here render a brand-coloured monogram instead, which covers the
 * restoration-specific systems (Xactimate, DASH, Encircle, DocuSketch, the TPA
 * networks) that no general icon set carries.
 *
 * The marks remain the trademarks of their owners and are used here only to
 * identify the system being connected.
 */

export interface BrandIcon {
  title: string;
  hex: string;
  /** SVG path data on a 24×24 viewBox. */
  path: string;
}

export const BRAND_ICONS: Record<string, BrandIcon> = {
${body}
};

export function brandIconFor(connectorId: string): BrandIcon | undefined {
  return BRAND_ICONS[connectorId];
}
`,
);

console.log(`Generated ${entries.length} brand icons -> src/patterns/brandIcons.ts`);
